#!/usr/bin/env python3
"""Generate the deterministic, toroidal 64x64 material blue-noise threshold map.

Uses void-and-cluster ranking with a Gaussian density kernel. Only the Python
standard library is needed; all optimization happens offline, never on Tab5.
"""
from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import math
from pathlib import Path
import random

ROOT = Path(__file__).resolve().parents[1]
SIZE = 64
COUNT = SIZE * SIZE
SEED = 20261027
SIGMA = 1.5


def generate() -> bytes:
    radius = math.ceil(SIGMA * 3)
    kernel = [(dx, dy, math.exp(-(dx * dx + dy * dy) / (2 * SIGMA * SIGMA)))
              for dy in range(-radius, radius + 1)
              for dx in range(-radius, radius + 1)]
    density = [0.0] * COUNT

    def update(index: int, sign: int) -> None:
        x, y = index % SIZE, index // SIZE
        for dx, dy, weight in kernel:
            target = ((y + dy) % SIZE) * SIZE + (x + dx) % SIZE
            density[target] += sign * weight

    rng = random.Random(SEED)
    occupied = set(rng.sample(range(COUNT), COUNT // 10))
    empty = set(range(COUNT)) - occupied
    for index in sorted(occupied):
        update(index, 1)

    # Relax the initial sparse pattern by moving its tightest cluster into its
    # largest void. Include the removed point in the void search to detect the
    # equilibrium directly. Index tie breaks make the output reproducible.
    for _ in range(COUNT * 4):
        cluster = max(occupied, key=lambda i: (density[i], -i))
        occupied.remove(cluster)
        empty.add(cluster)
        update(cluster, -1)
        void = min(empty, key=lambda i: (density[i], i))
        occupied.add(void)
        empty.remove(void)
        update(void, 1)
        if cluster == void:
            break
    else:
        raise RuntimeError("void-and-cluster relaxation did not converge")

    initial = occupied.copy()
    initial_density = density.copy()
    ranks = [-1] * COUNT
    for rank in range(len(initial) - 1, -1, -1):
        cluster = max(occupied, key=lambda i: (density[i], -i))
        ranks[cluster] = rank
        occupied.remove(cluster)
        update(cluster, -1)

    occupied = initial.copy()
    empty = set(range(COUNT)) - occupied
    density[:] = initial_density
    # Above 50% this is equivalent to removing the tightest cluster from the
    # complementary pattern: a toroidal kernel has the same total at each cell.
    for rank in range(len(initial), COUNT):
        void = min(empty, key=lambda i: (density[i], i))
        ranks[void] = rank
        occupied.add(void)
        empty.remove(void)
        update(void, 1)

    assert sorted(ranks) == list(range(COUNT))
    thresholds = bytes(rank >> 4 for rank in ranks)
    assert Counter(thresholds) == Counter({value: 16 for value in range(256)})
    return thresholds


def header(thresholds: bytes) -> str:
    digest = hashlib.sha256(thresholds).hexdigest()
    rows = ["  " + ", ".join(f"0x{value:02X}" for value in thresholds[i:i + 32]) + ","
            for i in range(0, COUNT, 32)]
    return "\n".join([
        "#pragma once", "", "#include <stdint.h>", "",
        "// Generated by tools/build_material_noise.py; do not edit the map.",
        f"// Toroidal void-and-cluster, seed={SEED}, sigma={SIGMA}, 64x64.",
        "// Every 8-bit threshold appears exactly 16 times. No runtime PRNG.",
        f"// SHA-256: {digest}",
        "namespace MaterialNoise {", "constexpr unsigned SIZE = 64;",
        "alignas(4) inline constexpr uint8_t thresholds[SIZE * SIZE] = {",
        *rows, "};", "}  // namespace MaterialNoise", "",
    ])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verify the checked-in map without changing files")
    args = parser.parse_args()
    values = generate()
    output = ROOT / "include/material_noise.h"
    source = header(values)
    if args.check:
        if not output.exists() or output.read_text() != source:
            raise SystemExit("material_noise.h differs; run tools/build_material_noise.py")
    else:
        output.write_text(source)
    print(f"{output.name}: 4096 bytes; 256 thresholds x 16; "
          f"sha256={hashlib.sha256(values).hexdigest()}")


if __name__ == "__main__":
    main()
