#!/usr/bin/env python3
"""Build original short, softly damped UI plucks; no external audio assets."""
from __future__ import annotations

import argparse
import math
from pathlib import Path
import struct
import wave

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "include/ui_sounds.h"
RATE = 48000
SPECS = [
    ("Press", 1046.50, 38, .12),
    ("PressHigh", 1318.51, 36, .10),
    ("Tick0", 1046.50, 17, .15),
    ("Tick1", 1174.66, 17, .15),
    ("Tick2", 1318.51, 17, .15),
    ("Tick3", 1567.98, 17, .15),
    ("Tick4", 1760.00, 17, .15),
    ("Direction", 987.77, 30, .08),
    ("Neutral", 659.25, 32, .06),
]


def pluck(frequency: float, milliseconds: int, noise: float) -> list[int]:
    length = RATE * milliseconds // 1000
    values, weights = [], []
    random_state = 0x51A8F00D
    for index in range(length):
        t = index / RATE
        unit = index / (length - 1)
        attack = min(1., t / .0012)
        release = min(1., (1 - unit) * milliseconds / 2)
        envelope = math.sin(attack * math.pi / 2) ** 2 * release ** 2 * math.exp(-5.5 * unit)
        random_state ^= (random_state << 13) & 0xffffffff
        random_state ^= random_state >> 17
        random_state ^= (random_state << 5) & 0xffffffff
        grain = (random_state / 0x7fffffff - 1) * math.exp(-30 * unit)
        body = (math.sin(math.tau * frequency * t)
                + .22 * math.sin(math.tau * frequency * 2.002 * t)
                + .055 * math.sin(math.tau * frequency * 3.01 * t))
        values.append(envelope * (body + noise * grain))
        weights.append(envelope)
    # Remove DC while preserving the zero-ended envelope.
    dc = sum(values) / sum(weights)
    values = [sample - dc * weight for sample, weight in zip(values, weights)]
    scale = 14000 / max(abs(sample) for sample in values)
    samples = [round(sample * scale) for sample in values]
    samples[0] = samples[-1] = 0
    assert len(samples) == length and max(map(abs, samples)) <= 14000
    assert abs(sum(samples)) < len(samples)
    return samples


def generate() -> tuple[str, dict[str, list[int]]]:
    lines = ["// Generated by tools/build_ui_sounds.py. Original synthesized UI sounds.",
             "#pragma once", "#include <cstdint>", "#include <cstddef>",
             "namespace UiSounds {", f"constexpr uint32_t SampleRate = {RATE};",
             "struct Clip { const int16_t* data; size_t size; };"]
    clips = {}
    for name, frequency, duration, noise in SPECS:
        clips[name] = samples = pluck(frequency, duration, noise)
        lines.append(f"inline constexpr int16_t {name}Data[] = {{")
        lines.extend("  " + ",".join(map(str, samples[i:i+20])) + ","
                     for i in range(0, len(samples), 20))
        lines.extend(["};", f"inline constexpr Clip {name}{{{name}Data,sizeof({name}Data)/sizeof(int16_t)}};"])
    lines.extend(["inline constexpr Clip Ticks[] = {Tick0,Tick1,Tick2,Tick3,Tick4};", "} // namespace UiSounds", ""])
    return "\n".join(lines), clips


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--preview", type=Path)
    args = parser.parse_args()
    source, clips = generate()
    if args.check:
        assert OUTPUT.read_text() == source, "Regenerate ui_sounds.h"
    else:
        OUTPUT.write_text(source)
    if args.preview:
        sequence = ["Press", "PressHigh", "Tick0", "Tick1", "Tick2", "Tick3", "Tick4", "Direction", "Neutral"]
        silence = [0] * (RATE // 5)
        samples = silence + [value for name in sequence for value in clips[name] + silence]
        args.preview.parent.mkdir(parents=True, exist_ok=True)
        with wave.open(str(args.preview), "wb") as output:
            output.setnchannels(1); output.setsampwidth(2); output.setframerate(RATE)
            output.writeframes(struct.pack(f"<{len(samples)}h", *samples))
    print(f"Original UI plucks: {len(clips)} clips, {sum(map(len,clips.values()))*2} PCM bytes, {RATE}Hz")


if __name__ == "__main__":
    main()
